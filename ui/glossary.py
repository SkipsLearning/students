FAQ = [
    ("Почему нельзя просто взять одну лучшую модель?",
     "Можно — в задаче банка так и вышло: лучше всех ансамбль нейросетей. Единая модель выигрывает, "
     "когда данных разного вида много (карты, счёт, анкета…), а в задаче банка источник один — кредитная история."),
    ("Разница 74 и 76 из 100 — это много?",
     "Для банка да. На 10 000 выданных кредитов это примерно на 15 невозвратов меньше, "
     "а у крупного банка кредитов — миллионы."),
    ("Откуда данные?",
     "Задача банка — реальные обезличенные данные соревнования Альфа-Банка. Home Credit — открытое соревнование "
     "Kaggle. Учебные данные сгенерированы, чтобы показать работу с пятью источниками."),
    ("Почему модель ошиблась на конкретном клиенте?",
     "Модель даёт вероятность, а не приговор. Клиент с риском 10% чаще всего возвращает кредит. "
     "Точность модели видна только на тысячах клиентов."),
]


def render() -> None:
    st.title("Словарь и вопросы")
    query = st.text_input("Найти термин", placeholder="например: AUC, GRU, эмбеддинг",
                          icon=":material/search:").strip().lower()
    found = [(t, d) for t, d in TERMS if query in t.lower() or query in d.lower()]
    if not found:
        st.caption("Ничего не нашлось — попробуйте другое слово.")
    cols = st.columns(2)
    for j, (term, text) in enumerate(found):
        with cols[j % 2].container(border=True):
            st.markdown(f"**{term}**  \n{text}")
    st.header("Частые вопросы")
    for question, answer in FAQ:
        with st.expander(question):
            st.markdown(answer)
